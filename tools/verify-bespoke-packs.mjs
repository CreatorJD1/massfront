import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

/* Keeps the phrase "bespoke pack" honest.  Live semantic V2 coverage is useful,
   but it is not an authored asset triplet.  This tool deliberately reads the
   small declaration in the renderer rather than trying to execute browser code. */
const root=process.cwd();
const file=path.join(root,'src','engine','materials-v2.js');
const text=fs.readFileSync(file,'utf8');
const match=text.match(/const MF2_BESPOKE_PACKS=\{([\s\S]*?)\n\};\nconst MF2_BESPOKE_PACK=/);
if(!match)throw new Error('MF2_BESPOKE_PACKS declaration was not found');

const body=match[1];
const start=/^  ([A-Za-z0-9_]+):\{/gm;
const starts=[];
let found;
while((found=start.exec(body)))starts.push({id:found[1],index:found.index});
const packs=starts.map((pack,index)=>({
  id:pack.id,
  body:body.slice(pack.index,index+1<starts.length?starts[index+1].index:body.length)
}));
if(!packs.length)throw new Error('No declared bespoke packs found');

let failures=0;
let authored=0;
let prototype=0;
let template=0;
/* File presence proves a pack can load, not that it was painted or baked for
   the exact production mesh. The broad catalogue generated by
   build-bespoke-v2-textures.py uses a generic quadrant/panel layout; only the
   two imported reference assets currently satisfy the stricter UV-authored
   evidence gate. Keep the distinction in the verifier so release notes cannot
   accidentally turn placeholders into finished art. */
const UV_AUTHORED_REFERENCE=new Set(['novaHeavyTankV2','novaFactoryV2']);
function fail(message){ failures++;console.error('FAIL '+message); }
for(const pack of packs){
  const faction=pack.body.match(/faction:'([^']+)'/);
  const source=pack.body.match(/source:'([^']+)'/);
  const maps=pack.body.match(/maps:([^,\n]+)/);
  const uv=pack.body.match(/uv:'([^']+)'/);
  if(!faction)fail(`${pack.id}: missing faction provenance`);
  if(!source)fail(`${pack.id}: missing source provenance`);
  if(!maps)fail(`${pack.id}: missing maps/path field`);
  if(!uv)fail(`${pack.id}: missing UV provenance`);
  if(!source)continue;
  if(source[1]==='authored'){
    if(!maps||!/^'[^']+'$/.test(maps[1].trim())){
      fail(`${pack.id}: authored pack needs a map path prefix`);
      continue;
    }
    const prefix=maps[1].trim().slice(1,-1);
    for(const suffix of ['baseao','nre','masks']){
      const asset=path.join(root,'assets','textures','materials',`${prefix}-${suffix}.png`);
      if(!fs.existsSync(asset))fail(`${pack.id}: missing ${path.relative(root,asset)}`);
    }
    if(UV_AUTHORED_REFERENCE.has(pack.id)){
      authored++;
      if(!failures)console.log(`PASS ${pack.id}: verified imported-UV ${faction&&faction[1]} reference`);
    }else{
      template++;
      console.log(`TEMPLATE ${pack.id}: map triplet present, but exact-mesh UV authorship is not yet verified`);
    }
  }else if(source[1]==='semantic-bake'){
    prototype++;
    if(!uv||uv[1]!=='generated-islands')fail(`${pack.id}: semantic bake needs generated-islands UV provenance`);
    console.log(`PROTO ${pack.id}: semantic bake; not counted as an authored texture pack`);
  }else fail(`${pack.id}: unsupported source '${source[1]}'`);
}
console.log(`MF2 bespoke packs: ${authored} verified UV-authored, ${template} generated/unverified templates, ${prototype} prototype, ${failures} failure(s)`);
if(failures)process.exitCode=1;
