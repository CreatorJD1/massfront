/* ============================================================================
   CONVERT WORLD ASSET REBUILDS -> ENGINE DATA
   ----------------------------------------------------------------------------
   Reads the engine.json files produced by the asset-rebuild pipeline and emits
   src/engine/models-world-data.js: a single file of JS objects/arrays that the
   runtime loader turns into InstMesh geometry.

   Why not binary?  The source JSON is only ~2.3 MB; keeping it as JS keeps the
   loader tiny and avoids an extra decode step on every boot.  The runtime
   still builds Float32Array vertex buffers once at init.
   ============================================================================ */
import fs from 'fs';
import path from 'path';

const SRC_DIR = 'source-media/world-asset-rebuilds/engine-json';
const OUT_FILE = 'src/engine/models-world-data.js';
const RUNTIME_UV_SCALE = 0.055;

const MAT_MAP = {
  PLATE:0, GREEBLE:1, TREAD:2, TRIM:3,
  GLASS:4, LAMP:5,   CONC:6,  RUST:7,
  CHITIN:8, EARTH:9, WARN:10, BRASS:11,
  STONE:12, LEAF:13,  SAND:14, CRYST:15,
  BUILD:16, ROOF:17,
  SERVO:18,
  TWR_ARMOR:19, TWR_MACH:20, TWR_COAT:21,
  TWR_GLOW:22,  TWR_PAD:23,  TWR_BORE:24
};

function fail(msg){ console.error(msg); process.exit(1); }
function finiteArray(a,n,label,file){
  if(!Array.isArray(a)||a.length!==n||a.some(v=>Array.isArray(v)?v.some(x=>!Number.isFinite(x)):!Number.isFinite(v)))
    fail(`${label} must contain ${n} finite entries in ${file}`);
}
/* Imported PBR UVs address a dedicated 0..1 texture set. The live material
   shader addresses one tiled atlas cell and calls fract(), so reusing those
   UVs stretches a window bay over an eighty-metre wall. Curated exports are
   triangle-split; give every face world-density planar coordinates instead. */
function runtimePlanarUV(data,file){
  const uv=Array.from({length:data.vertexCount},()=>null),used=new Uint8Array(data.vertexCount);
  for(let at=0;at<data.indices.length;at+=3){
    const ids=data.indices.slice(at,at+3);
    for(const id of ids){if(used[id])fail(`runtime atlas import requires triangle-split vertices; shared vertex ${id} in ${file}`);used[id]=1;}
    const p=ids.map(id=>data.positions[id]);
    const ab=[p[1][0]-p[0][0],p[1][1]-p[0][1],p[1][2]-p[0][2]];
    const ac=[p[2][0]-p[0][0],p[2][1]-p[0][1],p[2][2]-p[0][2]];
    const n=[ab[1]*ac[2]-ab[2]*ac[1],ab[2]*ac[0]-ab[0]*ac[2],ab[0]*ac[1]-ab[1]*ac[0]];
    const ax=Math.abs(n[0]),ay=Math.abs(n[1]),az=Math.abs(n[2]);
    if(Math.hypot(...n)<1e-7)fail(`degenerate triangle ${at/3} in ${file}`);
    const axes=ay>=ax&&ay>=az?[0,2]:ax>=az?[2,1]:[0,1];
    for(let k=0;k<3;k++)uv[ids[k]]=[p[k][axes[0]]*RUNTIME_UV_SCALE,p[k][axes[1]]*RUNTIME_UV_SCALE];
  }
  if(uv.some(v=>!v))fail(`unreferenced vertex in ${file}`);
  return uv.flat();
}
function boundsOf(data){
  const lo=[Infinity,Infinity,Infinity],hi=[-Infinity,-Infinity,-Infinity];
  for(const p of data.positions)for(let q=0;q<3;q++){lo[q]=Math.min(lo[q],p[q]);hi[q]=Math.max(hi[q],p[q]);}
  return {lo,hi,size:hi.map((v,q)=>v-lo[q])};
}

const files = fs.readdirSync(SRC_DIR)
  .filter(f => f.endsWith('.engine.json'))
  .map(f => ({ file:f, data:JSON.parse(fs.readFileSync(path.join(SRC_DIR,f),'utf8')) }));

if(!files.length) fail('no .engine.json files found in '+SRC_DIR);

const out = [];
out.push('/* AUTO-GENERATED by tools/convert-world-assets.mjs — do not edit */');
out.push('const WORLD_MODELS={');

for(const {file,data} of files){
  const name = data.name;
  if(!name) fail('missing name in '+file);
  if(data.coordinateSystem!=='Y-up')fail(`coordinateSystem must be Y-up in ${file}`);
  if(!Number.isInteger(data.vertexCount)||data.vertexCount<3||data.vertexCount>65535)fail(`invalid vertexCount in ${file}`);
  finiteArray(data.positions,data.vertexCount,'positions',file);
  finiteArray(data.normals,data.vertexCount,'normals',file);
  if(!Array.isArray(data.indices)||data.indices.length%3||data.indices.some(i=>!Number.isInteger(i)||i<0||i>=data.vertexCount))
    fail(`indices must be in-range triangles in ${file}`);
  const bounds=boundsOf(data),contactY=data.contactY===undefined?bounds.lo[1]:data.contactY;
  if(!Number.isFinite(contactY)||contactY<bounds.lo[1]-.01||contactY>bounds.hi[1])fail(`invalid contactY in ${file}`);

  // Resolve per-vertex material names.
  const names = [];
  if(Array.isArray(data.materialNames)){
    names.push(...data.materialNames);
  }else if(data.materialFlags && data.materialFlagLegend){
    const legend = data.materialFlagLegend;
    for(const f of data.materialFlags) names.push(legend[String(f)] || 'PLATE');
  }else{
    // No material info: default everything to PLATE so it at least renders.
    names.length = data.vertexCount;
    names.fill('PLATE');
  }
  if(names.length !== data.vertexCount) fail(`material name count ${names.length} != vertex count ${data.vertexCount} in ${file}`);

  // Resolve per-vertex material IDs (+1 because engine stores MAT+1, boneless).
  const mats = names.map(n => {
    const id = MAT_MAP[n];
    if(id === undefined) fail(`unknown material "${n}" in ${file}`);
    return id + 1;
  });

  // Build compact arrays: positions flattened, normals flattened, uv0 flattened (or zeros), indices, material ids.
  const pos = data.positions.flat();
  const nrm = data.normals.flat();
  const uv0 = runtimePlanarUV(data,file);
  /* Keep the asset's authored, non-overlapping UV0 beside the world-density
     coordinates used by the legacy tiled atlas. Material V2 scenery samples
     unique baked Base/AO + Normal/Rough/Emissive + mask maps; throwing this UV
     set away forced every facade back through one repeating concrete tile and
     made the five individual structures look like recolours of one building.
     Legacy loading still reads `uv`, so this addition is backwards compatible. */
  const authored = Array.isArray(data.uv0) && data.uv0.length===data.vertexCount
    ? data.uv0.flat() : null;
  /* Scenery rebuilt before the authored-PBR pass (rocks, crystals, berms) has
     no unique UV0 and stays on the tiled legacy coordinates. Only the five
     structure assets are required to carry authored UVs. */
  const wantsAuthored=/mdlCity|mdlCivic/.test(name);
  if(wantsAuthored&&(!authored||authored.length!==data.vertexCount*2||authored.some(v=>!Number.isFinite(v))))
    fail(`authored uv0 must contain ${data.vertexCount} finite vec2 entries in ${file}`);
  const uv2=authored&&authored.length===data.vertexCount*2?authored:uv0;
  const idx = data.indices;

  out.push(`  ${name}:{`);
  out.push(`    vertexCount:${data.vertexCount},`);
  out.push(`    indexCount:${idx.length},`);
  out.push(`    instanceCap:${data.instanceCap || 240},`);
  out.push(`    contactY:${+contactY.toFixed(6)},`);
  out.push(`    bounds:[[${bounds.lo.map(v=>+v.toFixed(4)).join(',')}],[${bounds.hi.map(v=>+v.toFixed(4)).join(',')}]],`);
  out.push(`    uvMode:'runtime-planar',`);
  out.push(`    dimensions:[${(data.dimensions ? [data.dimensions.x,data.dimensions.y,data.dimensions.z] : [0,0,0]).map(v=>+v.toFixed(4)).join(',')}],`);
  out.push(`    pos:[${pos.map(v=>+v.toFixed(6)).join(',')}],`);
  out.push(`    nrm:[${nrm.map(v=>+v.toFixed(6)).join(',')}],`);
  out.push(`    uv:[${uv0.map(v=>+v.toFixed(6)).join(',')}],`);
  out.push(`    uv2:[${uv2.map(v=>+v.toFixed(6)).join(',')}],`);
  out.push(`    idx:[${idx.join(',')}],`);
  out.push(`    mat:[${mats.join(',')}]`);
  out.push('  },');
  console.log('converted', name, data.vertexCount, 'verts', idx.length, 'indices');
}

out.push('};');
fs.writeFileSync(OUT_FILE, out.join('\n'));
console.log('wrote', OUT_FILE, '('+Math.round(fs.statSync(OUT_FILE).size/1024)+' KB)');
