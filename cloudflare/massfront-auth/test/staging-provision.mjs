#!/usr/bin/env node
/* ============================================================================
   MASSFRONT auth worker — DISPOSABLE STAGING PROVISION + REAL-WORKER E2E
   ----------------------------------------------------------------------------
   One repeatable command that stands up a throwaway Cloudflare staging stack,
   proves the social/lobby surface against it over real HTTPS, and tears it back
   down. It exists so "is the Worker production-ready" can be answered with a
   deployed artifact instead of a local emulator.

       node test/staging-provision.mjs --confirm         # create, test, destroy
       node test/staging-provision.mjs --confirm --keep  # leave it standing
       node test/staging-provision.mjs                   # dry run: print the plan

   WHY IT REFUSES TO RUN WITHOUT --confirm
   Everything below creates real, billable, internet-reachable resources in
   whichever Cloudflare account `wrangler whoami` resolves to. That is a
   deliberate speed bump, not ceremony.

   THE PRODUCTION GUARD IS THE POINT OF THIS FILE
   The repo's wrangler.toml is the PRODUCTION config: name = "massfront-auth"
   bound to the production D1 `database_id`. A staging deploy that accidentally
   used it would overwrite the live accounts service, and a `--remote` migration
   against that id would rewrite real user rows. So this script:
     * never reads wrangler.toml — it writes its own wrangler.staging.toml,
     * hard-refuses if the worker name or database id it is about to touch
       matches the production values,
     * passes `-c wrangler.staging.toml` to migrations/deploy, and teardown
       addresses only the strict generated staging names (never config defaults).

   THE DEV_ECHO_CODE EXPOSURE, STATED PLAINLY
   The E2E has to complete e-mail verification, and no mail provider is wired
   up, so the staging Worker is deployed with DEV_ECHO_CODE=1 — which makes
   POST /verify/request hand the six-digit code back in its own response body.
   For as long as that Worker is reachable, anyone who finds the URL can verify
   any address. That is acceptable for a short-lived disposable stack and is
   NEVER acceptable on production. --keep prints a loud reminder for exactly
   this reason, and the default path destroys the stack immediately.
   ============================================================================ */
import { execFileSync } from 'node:child_process';
import { writeFileSync, rmSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const HERE = resolve(fileURLToPath(new URL('..', import.meta.url)));
const argv = process.argv.slice(2);
const has = f => argv.includes('--' + f);
const CONFIRM = has('confirm'), KEEP = has('keep');

/* The two values this script must never touch. */
const PROD_WORKER = 'massfront-auth';
const PROD_DB_ID = 'e3c74e0d-59b8-427e-92b8-ea8a3bbd6573';

const STAMP = Date.now().toString(36);
const STAGING_WORKER = `massfront-auth-staging-${STAMP}`;
const STAGING_DB = `massfront-staging-${STAMP}`;
const CFG = join(HERE, 'wrangler.staging.toml');
/* Invoke Wrangler's JavaScript entry point through the current Node runtime.
   Calling node_modules/.bin/wrangler directly is not portable: on Windows the
   generated shim is wrangler.cmd, which execFileSync cannot execute without a
   shell. Keeping shell:false also avoids quoting generated resource names. */
const WRANGLER = join(HERE, 'node_modules', 'wrangler', 'bin', 'wrangler.js');

/* The ledger is applied ONCE, by wrangler, in one command. The old list of
   hand-run files is gone: schema.sql is now only a snapshot, and replaying
   legacy 0001 would fail on `duplicate column name`. A staging database is
   fresh, so migrations-ledger/0001-production-baseline builds the Aug-19
   schema from nothing and 0002/0003 add to it — the same path production
   takes, which is the only reason staging is worth anything. */
const LEDGER_APPLY = ['d1', 'migrations', 'apply'];

/**
 * Destructive cleanup is allowed only for names generated by this harness.
 * The prefix check is deliberately stricter than a simple production-name
 * inequality so a future caller cannot accidentally pass an arbitrary target.
 */
export function assertDisposableTargets(workerName, databaseName, databaseId = null) {
  if (workerName === PROD_WORKER || !/^massfront-auth-staging-[a-z0-9]+$/.test(workerName)) {
    throw new Error(`refusing cleanup of non-disposable worker name: ${workerName}`);
  }
  if (!/^massfront-staging-[a-z0-9]+$/.test(databaseName)) {
    throw new Error(`refusing cleanup of non-disposable database name: ${databaseName}`);
  }
  if (databaseId && databaseId.toLowerCase() === PROD_DB_ID.toLowerCase()) {
    throw new Error('refusing cleanup: disposable stack resolved to the PRODUCTION database id');
  }
}

/** --keep is honored only after a completely successful, addressable run. */
export function shouldKeepDisposableStack({ keepRequested, failed, databaseCreated, deploySucceeded, deployedUrl }) {
  return Boolean(keepRequested && !failed && databaseCreated && deploySucceeded && deployedUrl);
}

/* Wrangler reports deletion of an already-absent disposable resource as an
   error. Treat only its explicit missing-resource responses as success so an
   authentication or transport failure can never be mistaken for cleanup. */
export function isMissingDisposableResource(error) {
  const text = [error && error.message, error && error.stdout, error && error.stderr]
    .filter(Boolean).join('\n');
  return /d1 database lookup database not found/i.test(text)
    || /worker(?: script)?[^\n]*(?:does not exist|not found)/i.test(text);
}

/**
 * Delete by the independently-known generated names. Neither deletion depends
 * on a parsed workers.dev URL or database UUID. This is intentionally callable
 * with `*MayExist` after an interrupted/ambiguous Wrangler command.
 */
export function teardownDisposableStack({
  workerName,
  databaseName,
  databaseId = null,
  workerMayExist,
  databaseMayExist,
  configPath,
  runWrangler,
  fileExists = existsSync,
  removeFile = rmSync,
  log = console,
}) {
  assertDisposableTargets(workerName, databaseName, databaseId);
  const errors = [];

  if (workerMayExist) {
    try {
      runWrangler(['delete', workerName, '--force']);
      log.log('deleted worker ' + workerName);
    } catch (error) {
      if (isMissingDisposableResource(error)) log.log('worker already absent ' + workerName);
      else {
        errors.push({ resource: 'worker', error });
        log.error('worker teardown failed — delete it by hand: ' + workerName);
      }
    }
  }

  if (databaseMayExist) {
    try {
      runWrangler(['d1', 'delete', databaseName, '-y']);
      log.log('deleted database ' + databaseName);
    } catch (error) {
      if (isMissingDisposableResource(error)) log.log('database already absent ' + databaseName);
      else {
        errors.push({ resource: 'database', error });
        log.error('database teardown failed — delete it by hand: ' + databaseName);
      }
    }
  }

  /* Preserve the generated config after a teardown error for manual recovery. */
  if (!errors.length) {
    try { if (fileExists(configPath)) removeFile(configPath); } catch (error) {
      errors.push({ resource: 'config', error });
      log.error('staging config cleanup failed: ' + configPath);
    }
  }
  return errors;
}

function wrangler(args, { capture = true } = {}) {
  return execFileSync(process.execPath, [WRANGLER, ...args], {
    cwd: HERE, encoding: 'utf8', stdio: capture ? 'pipe' : 'inherit', maxBuffer: 32 * 1024 * 1024,
  });
}

const PLAN = [
  `1. wrangler d1 create ${STAGING_DB}`,
  `2. write wrangler.staging.toml  (name=${STAGING_WORKER}, the NEW database_id, social flags on, DEV_ECHO_CODE=1)`,
  `3. wrangler d1 migrations apply ${STAGING_DB} --remote -c wrangler.staging.toml   (the ledger, once)`,
  '4. wrangler deploy -c wrangler.staging.toml',
  '5. node test/e2e-worker.mjs --base https://<deployed-url>',
  `6. wrangler delete ${STAGING_WORKER} --force  +  wrangler d1 delete ${STAGING_DB}`,
];

export function runStagingProvision(options = {}) {
  const confirm = options.confirm ?? CONFIRM;
  const keep = options.keep ?? KEEP;
  const workerName = options.workerName ?? STAGING_WORKER;
  const databaseName = options.databaseName ?? STAGING_DB;
  const configPath = options.configPath ?? CFG;
  const runWrangler = options.runWrangler ?? wrangler;
  const writeConfig = options.writeConfig ?? writeFileSync;
  const fileExists = options.fileExists ?? existsSync;
  const removeFile = options.removeFile ?? rmSync;
  const log = options.log ?? console;
  const runE2e = options.runE2e ?? (deployedUrl => execFileSync(
    process.execPath,
    [join(HERE, 'test', 'e2e-worker.mjs'), '--base', deployedUrl],
    { cwd: HERE, stdio: 'inherit' },
  ));

  assertDisposableTargets(workerName, databaseName);

  if (!confirm) {
    log.log('DRY RUN — nothing was created. Plan:\n');
    for (const step of PLAN) log.log('   ' + step);
    log.log('\nRe-run with --confirm to execute. Production is never touched:');
    log.log(`   guarded worker name : ${PROD_WORKER}`);
    log.log(`   guarded database id : ${PROD_DB_ID}`);
    return 0;
  }

  let dbId = null, deployedUrl = null, failed = null;
  let databaseCreateAttempted = false, databaseCreated = false;
  let workerDeployAttempted = false, deploySucceeded = false;
  try {
    /* ---- 1. disposable D1 ------------------------------------------------- */
    log.log(`creating disposable D1 ${databaseName} ...`);
    databaseCreateAttempted = true;
    const created = runWrangler(['d1', 'create', databaseName]);
    databaseCreated = true; // independent of parsing the UUID below
    const m = created.match(/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})/i);
    if (!m) throw new Error('could not parse a database_id out of `d1 create` output:\n' + created);
    dbId = m[1];
    assertDisposableTargets(workerName, databaseName, dbId);
    log.log('  database_id ' + dbId);

    /* ---- 2. its own config, guarded --------------------------------------- */
    writeConfig(configPath, [
      '# GENERATED by test/staging-provision.mjs — disposable. Do not commit.',
      `name = "${workerName}"`,
      'main = "src/index.js"',
      'compatibility_date = "2026-01-01"',
      '',
      '[[d1_databases]]',
      'binding       = "DB"',
      `database_name = "${databaseName}"`,
      `database_id   = "${dbId}"`,
      /* Per-DATABASE, not top level. Wrangler silently falls back to ./migrations
         and reports "No migrations folder found" if this sits anywhere else. */
      'migrations_dir = "migrations-ledger"',
      '',
      '[vars]',
      'SOCIAL_CHAT_ENABLED = "1"',
      'SOCIAL_PRESENCE_ENABLED = "1"',
      'MULTIPLAYER_LOBBIES_ENABLED = "1"',
      'MULTIPLAYER_INVITES_ENABLED = "1"',
      '# Staging only. Hands verification codes to any caller — never on production.',
      'DEV_ECHO_CODE = "1"',
      '',
      '[limits]',
      'cpu_ms = 50',
      '',
    ].join('\n'));
    log.log('  wrote ' + configPath);

    /* ---- 3. migrations against the NEW database only ---------------------- */
    log.log('applying the migration ledger (one command, ordered, recorded) ...');
    runWrangler([...LEDGER_APPLY, databaseName, '--remote', '-c', configPath]);

    /* ---- 4. deploy --------------------------------------------------------- */
    log.log('deploying ' + workerName + ' ...');
    workerDeployAttempted = true;
    const dep = runWrangler(['deploy', '-c', configPath]);
    deploySucceeded = true; // independent of parsing the public URL below
    const urlMatch = dep.match(/https:\/\/[a-z0-9.-]+\.workers\.dev/i);
    deployedUrl = urlMatch ? urlMatch[0] : null;
    if (!deployedUrl) throw new Error('deploy produced no workers.dev URL:\n' + dep);
    log.log('  ' + deployedUrl);

    /* ---- 5. the SAME e2e suite, now over real HTTPS ------------------------ */
    log.log('running test/e2e-worker.mjs against the deployed worker ...\n');
    runE2e(deployedUrl);
  } catch (error) {
    failed = error;
    log.error('\nSTAGING RUN FAILED: ' + (error && error.message ? error.message.slice(0, 400) : String(error)));
  } finally {
    /* ---- 6. teardown ------------------------------------------------------- */
    const keepStack = shouldKeepDisposableStack({
      keepRequested: keep,
      failed,
      databaseCreated,
      deploySucceeded,
      deployedUrl,
    });
    if (keepStack) {
      log.log('\n--keep: leaving the stack standing.');
      log.log('  !! It is deployed with DEV_ECHO_CODE=1 — anyone with the URL can verify any address.');
      log.log('  destroy it with these exact generated names:');
      log.log(`     npx wrangler delete ${workerName} --force`);
      log.log(`     npx wrangler d1 delete ${databaseName} -y`);
    } else {
      if (keep) log.error('\n--keep ignored because provisioning/E2E did not finish safely; tearing down.');
      try {
        const cleanupErrors = teardownDisposableStack({
          workerName,
          databaseName,
          databaseId: dbId,
          workerMayExist: workerDeployAttempted,
          databaseMayExist: databaseCreateAttempted,
          configPath,
          runWrangler,
          fileExists,
          removeFile,
          log,
        });
        if (cleanupErrors.length && !failed) {
          failed = new Error('disposable staging teardown failed; manual cleanup is required');
        }
      } catch (error) {
        if (!failed) failed = error;
        log.error('staging teardown safety check failed: ' + error.message);
      }
    }
  }
  return failed ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(SCRIPT_PATH)) {
  process.exitCode = runStagingProvision();
}
